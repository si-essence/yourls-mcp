#!/usr/bin/env node
/**
 * Generate src/operations.ts from yourls.routes.json (YOURLS 1.10.6 core
 * API actions from yourls-api.php). Run: node scripts/gen-operations.mjs
 *
 * Every request is POST yourls-api.php with format=json. shorturl is a write.
 * Plugin actions live in exclusions, not in OPERATIONS.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const specPath = join(root, "yourls.routes.json");

export const DEFAULT_TOOLSETS = ["meta", "stats", "links"];
export const ALL_TOOLSETS = ["links", "meta", "stats"];
export const API_PATH = "yourls-api.php";

/**
 * @typedef {{ name: string, type: string, required: boolean }} Field
 * @typedef {{
 *   action: string,
 *   yourlsAction: string,
 *   toolset: string,
 *   write: boolean,
 *   destructive: boolean,
 *   summary: string,
 *   fields: Field[],
 *   sampleParams: Record<string, string>,
 * }} ActionRow
 * @typedef {{
 *   source: string,
 *   version: string,
 *   core: string[],
 *   actions: ActionRow[],
 *   exclusions: { action: string, reason: string }[],
 * }} Spec
 */

/**
 * @param {Spec} spec
 */
export function planOperations(spec) {
  const rows = spec.actions.map((action) => {
    const tool = `yourls_${action.toolset}`;
    return {
      method: "POST",
      path: API_PATH,
      tool,
      action: action.action,
      yourlsAction: action.yourlsAction,
      toolset: action.toolset,
      write: action.write,
      destructive: action.destructive,
      summary: action.summary,
      fields: action.fields,
      sampleParams: action.sampleParams ?? {},
      warnings: action.write ? ["This creates a short URL. It writes to the YOURLS database."] : [],
    };
  });
  return { rows, exclusions: spec.exclusions };
}

/**
 * @param {unknown} value
 * @param {number} indent
 */
function dump(value, indent) {
  const pad = " ".repeat(indent);
  if (value === null) return "null";
  if (typeof value === "string") return JSON.stringify(value);
  if (typeof value === "number" || typeof value === "boolean") return String(value);
  if (Array.isArray(value)) {
    if (value.length === 0) return "[]";
    const inner = value.map((item) => `${pad}  ${dump(item, indent + 2)}`).join(",\n");
    return `[\n${inner},\n${pad}]`;
  }
  if (typeof value === "object") {
    const entries = Object.entries(value);
    if (entries.length === 0) return "{}";
    const inner = entries
      .map(([key, entry]) => `${pad}  ${key}: ${dump(entry, indent + 2)}`)
      .join(",\n");
    return `{\n${inner},\n${pad}}`;
  }
  throw new Error("cannot dump value");
}

/**
 * @param {ReturnType<typeof planOperations>} plan
 * @param {Spec} spec
 */
function emitFile(plan, spec) {
  const counts = {};
  for (const row of plan.rows) {
    const current = counts[row.toolset] ?? { operations: 0, actions: [] };
    current.operations += 1;
    current.actions.push(row.yourlsAction);
    counts[row.toolset] = current;
  }
  const lines = [];
  lines.push(
    `/** Generated by scripts/gen-operations.mjs from yourls.routes.json (YOURLS ${spec.version} API). Do not edit by hand. */`,
    ``,
    `import { ConnectorError } from "./errors.js";`,
    ``,
    `export type HttpMethod = "GET" | "POST" | "PUT" | "PATCH" | "DELETE";`,
    ``,
    `export interface FieldSchema {`,
    `  readonly name: string;`,
    `  readonly type: string;`,
    `  readonly required: boolean;`,
    `}`,
    ``,
    `export interface Operation {`,
    `  readonly method: HttpMethod;`,
    `  readonly path: string;`,
    `  readonly tool: string;`,
    `  readonly action: string;`,
    `  readonly yourlsAction: string;`,
    `  readonly toolset: string;`,
    `  readonly write: boolean;`,
    `  readonly destructive: boolean;`,
    `  readonly summary: string;`,
    `  readonly fields: readonly FieldSchema[];`,
    `  readonly warnings: readonly string[];`,
    `  readonly sampleParams: Readonly<Record<string, string>>;`,
    `}`,
    ``,
    `export interface ExcludedOperation {`,
    `  readonly action: string;`,
    `  readonly reason: string;`,
    `}`,
    ``,
    `function row(`,
    `  action: string,`,
    `  options: {`,
    `    yourlsAction: string;`,
    `    toolset: string;`,
    `    write: boolean;`,
    `    destructive: boolean;`,
    `    summary: string;`,
    `    fields: readonly FieldSchema[];`,
    `    warnings: readonly string[];`,
    `    sampleParams: Readonly<Record<string, string>>;`,
    `  },`,
    `): Operation {`,
    `  return {`,
    `    method: "POST",`,
    `    path: "yourls-api.php",`,
    `    tool: \`yourls_\${options.toolset}\`,`,
    `    action,`,
    `    yourlsAction: options.yourlsAction,`,
    `    toolset: options.toolset,`,
    `    write: options.write,`,
    `    destructive: options.destructive,`,
    `    summary: options.summary,`,
    `    fields: options.fields,`,
    `    warnings: options.warnings,`,
    `    sampleParams: options.sampleParams,`,
    `  };`,
    `}`,
    ``,
    `export const DEFAULT_TOOLSETS = ${dump(DEFAULT_TOOLSETS, 0)} as const;`,
    ``,
    `export const ALL_TOOLSETS = ${dump(ALL_TOOLSETS, 0)} as const;`,
    ``,
    `export const CORE_ACTIONS = ${dump(spec.core, 0)} as const;`,
    ``,
    `export const TOOLSET_COUNTS: Readonly<`,
    `  Record<string, { readonly operations: number; readonly actions: readonly string[] }>`,
    `> = ${dump(counts, 0)};`,
    ``,
    `export const EXCLUSIONS: readonly ExcludedOperation[] = ${dump(plan.exclusions, 0)};`,
    ``,
    `export const OPERATIONS: readonly Operation[] = [`,
  );
  for (const row of plan.rows) {
    lines.push(`  row(${JSON.stringify(row.action)}, {`);
    lines.push(`    yourlsAction: ${JSON.stringify(row.yourlsAction)},`);
    lines.push(`    toolset: ${JSON.stringify(row.toolset)},`);
    lines.push(`    write: ${row.write},`);
    lines.push(`    destructive: ${row.destructive},`);
    lines.push(`    summary: ${JSON.stringify(row.summary)},`);
    lines.push(`    fields: ${dump(row.fields, 4)},`);
    lines.push(`    warnings: ${dump(row.warnings, 4)},`);
    lines.push(`    sampleParams: ${dump(row.sampleParams, 4)},`);
    lines.push(`  }),`);
  }
  lines.push(
    `];`,
    ``,
    `export function toolNames(): string[] {`,
    `  return [...new Set(OPERATIONS.map((operation) => operation.tool))].sort();`,
    `}`,
    ``,
    `export function operationsForTool(name: string): Operation[] {`,
    `  return OPERATIONS.filter((operation) => operation.tool === name);`,
    `}`,
    ``,
    `export function toolIsWrite(name: string): boolean {`,
    `  return OPERATIONS.some((operation) => operation.tool === name && operation.write);`,
    `}`,
    ``,
    `export function requireOp(tool: string, action: string): Operation {`,
    `  const found = OPERATIONS.find(`,
    `    (operation) => operation.tool === tool && operation.action === action,`,
    `  );`,
    `  if (found === undefined) {`,
    `    throw new ConnectorError("input", \`Unknown YOURLS operation \${tool} \${action}.\`);`,
    `  }`,
    `  return found;`,
    `}`,
    ``,
    `export function parseToolsets(raw: string | undefined): readonly string[] {`,
    `  if (raw === undefined || raw.trim() === "") return [...DEFAULT_TOOLSETS];`,
    `  const trimmed = raw.trim();`,
    `  if (trimmed === "all") return [...ALL_TOOLSETS];`,
    `  const wanted = trimmed`,
    `    .split(",")`,
    `    .map((part) => part.trim())`,
    `    .filter((part) => part.length > 0);`,
    `  const allowed = new Set<string>(ALL_TOOLSETS);`,
    `  const unknown = wanted.filter((name) => !allowed.has(name));`,
    `  if (unknown.length > 0) {`,
    `    throw new ConnectorError("config", "Unknown YOURLS_TOOLSETS value.");`,
    `  }`,
    `  return [...new Set(wanted)];`,
    `}`,
    ``,
    `export function toolsForToolsets(enabled: readonly string[]): string[] {`,
    `  const allow = new Set(enabled);`,
    `  return toolNames().filter((name) => {`,
    `    const operation = OPERATIONS.find((row) => row.tool === name);`,
    `    return operation !== undefined && allow.has(operation.toolset);`,
    `  });`,
    `}`,
    ``,
  );
  return `${lines.join("\n")}\n`;
}

function main() {
  const spec = JSON.parse(readFileSync(specPath, "utf8"));
  const plan = planOperations(spec);
  writeFileSync(join(root, "src/operations.ts"), emitFile(plan, spec));
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) main();
